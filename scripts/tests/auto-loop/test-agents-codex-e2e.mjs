#!/usr/bin/env node
/**
 * test-agents-codex-e2e.mjs — E2E test for the codex adapter spawn/parse pipeline.
 *
 * Strategy: drop a fake `codex` binary into a fixtures dir, prepend that dir to
 * PATH, then call the real `scripts/auto-loop/agents/codex.mjs` adapter and
 * assert it spawned the fake binary and parsed its output (incl. token usage).
 *
 * Why not mock spawnSync directly? Because the goal is to exercise the actual
 * spawn → stdio → parse pipeline. Mocking spawnSync would defeat the purpose
 * (the codex adapter was never run end-to-end before this test landed).
 *
 * Cross-platform shim:
 *  - Unix: a tiny shell wrapper named `codex` that execs `node fake-codex.mjs "$@"`.
 *  - Windows: a copy of `node.exe` renamed to `codex.exe`. We then rely on
 *    NODE_OPTIONS=--require=<fake-codex-loader.cjs> to take over before Node
 *    tries to load the first argv as a script. The loader prints the same
 *    deterministic output as the Unix shim and `process.exit(0)`s.
 *    Why this dance? Node's spawnSync without `shell: true` cannot resolve
 *    `.cmd`/`.bat`/extensionless shims on Windows — only true PE binaries
 *    (.exe/.com). Renaming node.exe is the lightest reliable way to produce
 *    a real `.exe` we can drive with our own logic.
 *
 * Usage: node scripts/tests/auto-loop/test-agents-codex-e2e.mjs
 * Exit 0 = all passed, 1 = any failure.
 */

import {
  existsSync,
  mkdirSync,
  writeFileSync,
  chmodSync,
  copyFileSync,
} from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { platform } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const fixtureDir = resolve(__dirname, 'fixtures');
const fakeCodexJs = resolve(fixtureDir, 'fake-codex.mjs');
const isWindows = platform() === 'win32';

if (!existsSync(fixtureDir)) mkdirSync(fixtureDir, { recursive: true });
if (!existsSync(fakeCodexJs)) {
  console.error(`fake-codex.mjs missing at ${fakeCodexJs}`);
  process.exit(1);
}

// ─── Shim setup ──────────────────────────────────────────────────────────────

let extraEnv = {};

function ensureShim() {
  if (isWindows) {
    // Strategy: copy current node binary as `codex.exe`, then drive it with
    // NODE_OPTIONS=--require=<loader> so our logic runs before Node tries to
    // load the first non-flag argv as a script.
    const codexExe = resolve(fixtureDir, 'codex.exe');
    const loaderCjs = resolve(fixtureDir, 'fake-codex-loader.cjs');

    // The loader. process.argv layout when invoked as
    //   codex.exe exec --full-auto <prompt>
    // is [<codex.exe>, 'exec', '--full-auto', '<prompt>'] — so slice(1) gives
    // back the same args the Unix fake-codex.mjs sees via slice(2) of node argv.
    const loaderSrc = `// Auto-generated by test-agents-codex-e2e.mjs.
// Mirrors fake-codex.mjs but runs as a --require preload because Node, when
// invoked via a renamed copy of node.exe, treats the first non-flag argv as a
// script path (and resolves it relative to cwd). So argv layout for
//   codex.exe exec --full-auto <prompt>
// is [<codex.exe>, '<cwd>/exec' (path-resolved by Node), '--full-auto', '<prompt>'].
// We detect the synthetic "exec" verb by basename.
const path = require('path');
const argv = process.argv;
const verb = argv[1] ? path.basename(argv[1]) : '';
const flag = argv[2];
const prompt = argv[3] || '';
if (verb !== 'exec' || flag !== '--full-auto') {
  console.error('fake-codex (loader): expected \`exec --full-auto <prompt>\`, got argv=' + JSON.stringify(argv));
  process.exit(2);
}
process.stdout.write(\`fake-codex received: \${prompt.slice(0, 60)}\\n\`);
process.stdout.write('Implementation complete\\n');
process.stdout.write(JSON.stringify({
  usage: { input_tokens: 100, output_tokens: 50, cache_read_input_tokens: 0 },
}) + '\\n');
process.exit(0);
`;
    writeFileSync(loaderCjs, loaderSrc);

    if (!existsSync(codexExe)) {
      copyFileSync(process.execPath, codexExe);
    }

    // Prepend to PATH and inject NODE_OPTIONS for the child.
    extraEnv.PATH = `${fixtureDir};${process.env.PATH || ''}`;
    extraEnv.NODE_OPTIONS = `--require "${loaderCjs.replace(/\\/g, '/')}"`;
  } else {
    const shim = resolve(fixtureDir, 'codex');
    const src = `#!/bin/sh\nexec node "${fakeCodexJs}" "$@"\n`;
    writeFileSync(shim, src);
    chmodSync(shim, 0o755);
    extraEnv.PATH = `${fixtureDir}:${process.env.PATH || ''}`;
  }
}

ensureShim();

// Apply env to current process so the adapter's spawnSync child inherits it.
for (const [k, v] of Object.entries(extraEnv)) {
  process.env[k] = v;
}

// ─── Run test ────────────────────────────────────────────────────────────────

const codex = (await import('../../auto-loop/agents/codex.mjs')).default;

let passed = 0;
let failed = 0;

function assert(label, cond, detail = '') {
  if (cond) {
    console.log(`  ✓ ${label}`);
    passed++;
  } else {
    console.log(`  ✗ ${label}${detail ? ' — ' + detail : ''}`);
    failed++;
  }
}

console.log('Test: codex.invoke spawns fake codex shim and parses output');

const result = await codex.invoke({ prompt: 'hello world', timeout: 10_000 });

if (result.error) {
  console.log(`  (debug) stderr: ${JSON.stringify(result.error).slice(0, 200)}`);
}
console.log(`  (debug) status: ${result.status}`);
console.log(`  (debug) output (first 200 chars): ${JSON.stringify((result.output || '').slice(0, 200))}`);

assert('output non-empty', !!(result.output && result.output.length > 0));
assert('output contains echo marker', (result.output || '').includes('fake-codex received'));
assert('output contains "hello world" prompt', (result.output || '').includes('hello world'));
assert('output contains completion marker', (result.output || '').includes('Implementation complete'));
assert('status is 0', result.status === 0, `got ${result.status}`);
assert(
  'tokens parsed (input=100, output=50)',
  !!result.tokens && result.tokens.input === 100 && result.tokens.output === 50,
  `got ${JSON.stringify(result.tokens)}`,
);
assert(
  'tokens.cached === 0',
  !!result.tokens && result.tokens.cached === 0,
  `got ${JSON.stringify(result.tokens)}`,
);

console.log(`\n${'─'.repeat(50)}`);
console.log(`Results: ${passed} passed, ${failed} failed`);
process.exit(failed > 0 ? 1 : 0);
